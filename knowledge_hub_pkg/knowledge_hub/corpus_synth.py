class SeedRegistry:
    def __init__(self, seed: int = 20260723):
        self._rng = random.Random(seed)

    def build(self, scale: str) -> Registry:
        s = SCALES[scale]
        rng = self._rng
        reg = Registry()

        # People with a reports_to tree (roots = Site Director).
        for i in range(s["emp"]):
            role = _ROLES[i % len(_ROLES)]
            reg.employees.append({
                "employee_id": f"EMP-{10000 + i}",
                "full_name": f"{rng.choice(_FIRST)} {rng.choice(_LAST)}",
                "role": role,
                "email": None,          # filled after name known, below
                "reports_to": None,
                "site": SITE,
            })
        for e in reg.employees:
            first, last = e["full_name"].split(" ", 1)
            e["email"] = f"{first[0].lower()}{_slug(last).lower()}@diversifiedbotanics.example"
        directors = [e for e in reg.employees if e["role"] == "Site Director"] \
            or reg.employees[:1]
        for e in reg.employees:
            if e not in directors:
                e["reports_to"] = rng.choice(directors)["employee_id"]

        # Vendors + customers (Organizations, high-stakes ER).
        for i in range(s["ven"]):
            base = f"{rng.choice(_LAST)} {rng.choice(_ORG_SUFFIX)}"
            reg.vendors.append({
                "vendor_id": f"SUP-{1000 + i}", "vendor_name": base,
                "tax_id": f"{rng.randint(10, 99)}-{rng.randint(1000000, 9999999)}",
                "email": f"quality@{_slug(base).lower()}.example",
                "qualification_status": rng.choice(["Approved", "Conditional"]),
            })
        for i in range(s["cus"]):
            base = f"{rng.choice(_LAST)} {rng.choice(_ORG_SUFFIX)}"
            reg.customers.append({
                "customer_id": f"CUST-{2000 + i}", "customer_name": base,
                "tax_id": f"{rng.randint(10, 99)}-{rng.randint(1000000, 9999999)}",
                "customer_type": rng.choice(["Wholesale", "Retail", "Contract"]),
            })

        # Products, materials (with vendor links), equipment.
        for i in range(s["prod"]):
            bot = _BOTANICALS[i % len(_BOTANICALS)]
            form = rng.choice(_FORMS)
            strength = rng.choice([250, 300, 500, 600, 1000])
            reg.products.append({
                "product_code": f"FG-{4000 + i}",
                "product_name": f"{bot} {strength}mg {form}",
                "botanical": bot, "strength_mg": strength, "form": form,
            })
        for i in range(s["mat"]):
            bot = _BOTANICALS[i % len(_BOTANICALS)]
            vendor = rng.choice(reg.vendors)
            reg.materials.append({
                "material_id": f"BOT-{5000 + i}",
                "material_name": f"{bot} Extract (raw)",
                "lot_no": f"L{rng.randint(24, 26)}-{rng.randint(10000, 99999)}",
                "vendor_id": vendor["vendor_id"],
                "expiry": f"20{rng.randint(27, 29)}-{rng.randint(1,12):02d}-01",
            })
        for i in range(s["equip"]):
            name, code = _EQUIP[i % len(_EQUIP)]
            reg.equipment.append({
                "equipment_id": f"EQ-{code}-{i + 1:02d}",
                "equipment_name": name,
                "room_id": f"RM-{101 + (i % 6)}",
            })

        # SOPs with supersession chains (some Rev 02 supersede Rev 01).
        topics = _SOP_TOPICS[:s["sop"]]
        for i, (dept, title) in enumerate(topics):
            rev = rng.choice([1, 1, 2, 3])
            reg.sops.append({
                "sop_no": f"SOP-{dept}-{i + 1:03d}",
                "title": title, "dept": dept, "version": f"Rev {rev:02d}",
                "supersedes": f"Rev {rev - 1:02d}" if rev > 1 else None,
            })
        # Form templates.
        for fno, name in [("QA-035", "Deviation Report"),
                          ("F-CAPA-002", "CAPA Form"),
                          ("QC-018", "Out-of-Specification Report"),
                          ("QMS-125", "Change Control Form"),
                          ("ENG-051", "Equipment Cleaning Log"),
                          ("QA-060", "Batch Release Disposition"),
                          ("WH-022", "Supplier Corrective Action Request"),
                          ("PROD-041", "Batch Production Record")]:
            reg.forms.append({"form_no": fno, "form_name": name})

        self._plant_er_noise(reg, rng)
        return reg

    def _plant_er_noise(self, reg: Registry, rng: random.Random) -> None:
        """Deliberate hard cases (spec §1.4): the entities ER must get right."""
        if reg.vendors:
            v = reg.vendors[0]
            # Same org, two surface forms, SAME tax_id -> a match that name
            # similarity alone might miss / a key must catch.
            variant = v["vendor_name"].upper().replace(" INC", "").replace(
                " LLC", "")
            reg.er_noise.append({
                "kind": "org_variant_same_key", "entity": v["vendor_id"],
                "surface_a": v["vendor_name"], "surface_b": variant,
                "shared_key": {"tax_id": v["tax_id"]}, "match": True})
        if len(reg.vendors) >= 2:
            # Two DIFFERENT vendors reusing one supplier lot_no -> proves
            # lot_no alone is a weak key (hard negative).
            reg.er_noise.append({
                "kind": "shared_lot_diff_vendor",
                "entity_a": reg.vendors[0]["vendor_id"],
                "entity_b": reg.vendors[1]["vendor_id"],
                "shared_key": {"lot_no": "L25-40000"}, "match": False})
        if reg.employees:
            e = reg.employees[0]
            first, last = e["full_name"].split(" ", 1)
            reg.er_noise.append({
                "kind": "person_nickname_same_email", "entity": e["employee_id"],
                "surface_a": e["full_name"],
                "surface_b": f"{first[:3]}. {last}",
                "shared_key": {"email": e["email"]}, "match": True})


# ---------------------------------------------------------------------------
# Narrative generation (local model writes prose for a code-built brief)
# ---------------------------------------------------------------------------
_SOP_SECTIONS = ["Purpose", "Scope", "Responsibilities", "Definitions",
                 "Procedure", "References", "Revision History"]


class NarrativeGenerator:
    def __init__(self, model: Optional[str] = None, host: Optional[str] = None):
        import ollama
        self.model = model or settings.extraction_model
        self._client = ollama.Client(host=host or settings.ollama_host)

    def _write(self, instruction: str, max_words: int = 180) -> str:
        # Retry transient serving errors (a llama-server hiccup mid-way must
        # not kill a 40-minute full-scale generation run).
        import time as _time
        last: Exception | None = None
        for attempt in range(3):
            try:
                resp = self._client.chat(
                    model=self.model,
                    messages=[{"role": "user", "content": instruction}],
                    think=False, options={"temperature": 0.4})
                return resp.message.content.strip()
            except Exception as e:
                last = e
                _time.sleep(5 * (attempt + 1))
        raise RuntimeError(f"narrative generation failed after retries: {last}")

    # -- SOP: code owns the skeleton + refs; model writes each section's prose
    def sop(self, sop: dict, reg: Registry, rng: random.Random) -> str:
        equip = rng.choice(reg.equipment) if reg.equipment else None
        form = rng.choice(reg.forms) if reg.forms else None
        author = _pick_role(reg, "QA Reviewer", rng)
        approver = _pick_role(reg, "QA Manager", rng)
        refs = [s["sop_no"] for s in rng.sample(
            reg.sops, min(2, len(reg.sops))) if s["sop_no"] != sop["sop_no"]]

        lines = [f"# {sop['sop_no']} — {sop['title']}", "",
                 f"**Document number:** {sop['sop_no']}  ",
                 f"**Version:** {sop['version']}  ",
                 f"**Site:** {COMPANY}, {SITE}  ",
                 f"**Prepared by:** {author['full_name']} ({author['role']})  ",
                 f"**Approved by:** {approver['full_name']} ({approver['role']})  "]
        if sop["supersedes"]:
            lines.append(f"**Supersedes:** {sop['supersedes']}  ")
        lines.append("")

        brief = (f"You are writing a fictional GMP Standard Operating Procedure "
                 f"for {COMPANY}, a botanical supplement manufacturer. SOP "
                 f"{sop['sop_no']}, titled '{sop['title']}'. Write ONLY the "
                 f"body text of the '%s' section — no heading, no preamble, "
                 f"realistic GMP wording, concise.")
        for sec in _SOP_SECTIONS:
            lines.append(f"## {sec}")
            if sec == "References":
                lines.append(f"- 21 CFR Part 111")
                for r in refs:
                    lines.append(f"- {r}")
                if form:
                    lines.append(f"- Form {form['form_no']} ({form['form_name']})")
                lines.append("")
            elif sec == "Revision History":
                lines.append(f"- {sop['version']} — current effective version.")
                if sop["supersedes"]:
                    lines.append(f"- {sop['supersedes']} — superseded by "
                                 f"{sop['version']}.")
                lines.append("")
            elif sec == "Responsibilities":
                extra = (f" Mention that the {author['role']} prepares and the "
                         f"{approver['role']} approves this procedure.")
                lines.append(self._write(brief % sec + extra))
                lines.append("")
            elif sec == "Procedure" and equip:
                extra = (f" The procedure involves equipment {equip['equipment_id']} "
                         f"({equip['equipment_name']}) in room {equip['room_id']}. "
                         f"Use numbered steps.")
                lines.append(self._write(brief % sec + extra, max_words=260))
                lines.append("")
            else:
                lines.append(self._write(brief % sec))
                lines.append("")
        return "\n".join(lines)

    # -- Communication thread (deviation / release / recall ...)
    def comm(self, kind: str, reg: Registry, rng: random.Random,
             record_id: str) -> str:
        prod = rng.choice(reg.products)
        batch = f"B-2026-{rng.randint(1000, 9999)}"
        sender = rng.choice(reg.employees)
        recipient = _pick_role(reg, "QA Manager", rng)
        sop = rng.choice(reg.sops)
        subjects = {
            "deviation": f"[DEVIATION] {record_id} — {batch} {prod['product_name']} — investigation",
            "release": f"[BATCH RELEASE] {record_id} — {prod['product_code']} {batch} — DISPOSITION",
            "capa": f"[CAPA ASSIGNMENT] {record_id} — action owner assignment",
            "recall": f"[URGENT — RECALL] {prod['product_code']} affected lots",
            "audit": f"[AUDIT FINDING] {record_id} — response required",
        }
        subject = subjects.get(kind, f"[{kind.upper()}] {record_id}")
        instruction = (
            f"Write a SHORT fictional internal email (5-8 sentences) at {COMPANY}, "
            f"a botanical supplement maker. Type: {kind}. It concerns record "
            f"{record_id}, product {prod['product_name']} ({prod['product_code']}), "
            f"batch {batch}, and references procedure {sop['sop_no']}. From "
            f"{sender['full_name']} ({sender['role']}) to {recipient['full_name']} "
            f"({recipient['role']}). Realistic GMP quality tone. No signature block.")
        body = self._strip_headers(self._write(instruction, max_words=200))
        return (f"From: {sender['full_name']} <{sender['email']}>\n"
                f"To: {recipient['full_name']} <{recipient['email']}>\n"
                f"Subject: {subject}\n\n{body}\n")

    def comm_thread(self, kind: str, reg: Registry, rng: random.Random,
                    record_id: str, with_reply: bool) -> list[str]:
        """A thread: the original message, plus (optionally) the recipient's
        reply — same record id anchor, RE: subject, roles swapped."""
        original = self.comm(kind, reg, rng, record_id)
        if not with_reply:
            return [original]
        # Parse the envelope we own to swap the parties.
        head = dict(line.split(": ", 1) for line in
                    original.splitlines()[:3])
        reply_instruction = (
            f"Write a SHORT fictional reply email (3-5 sentences) in a GMP "
            f"quality thread at {COMPANY}. You are {head['To']} responding to "
            f"{head['From']} about record {record_id} ({kind}). Acknowledge, "
            f"state the decision or next step (e.g. investigation opened, "
            f"disposition, action owner assigned), and give a deadline. "
            f"No signature block.")
        body = self._strip_headers(self._write(reply_instruction, max_words=140))
        reply = (f"From: {head['To']}\nTo: {head['From']}\n"
                 f"Subject: RE: {head['Subject']}\n\n{body}\n")
        return [original, reply]

    @staticmethod
    def _strip_headers(body: str) -> str:
        # The model sometimes re-emits its own "Subject:"/"From:" header lines
        # inside the body; strip leading header-ish lines so we own the envelope.
        body_lines = body.splitlines()
        while body_lines and body_lines[0].split(":", 1)[0].strip().lower() in (
                "subject", "from", "to", "date", "re"):
            body_lines.pop(0)
        return "\n".join(body_lines).strip()

    # -- Completed form instance (header fields + model free-text body)
    def form(self, template: dict, reg: Registry, rng: random.Random,
             record_id: str) -> str:
        prod = rng.choice(reg.products)
        batch = f"B-2026-{rng.randint(1000, 9999)}"
        equip = rng.choice(reg.equipment)
        raised = rng.choice(reg.employees)
        sop = rng.choice(reg.sops)
        lines = [f"# {template['form_name']} — {record_id}", "",
                 f"**Form number:** {template['form_no']}  ",
                 f"**Record ID:** {record_id}  ",
                 f"**Product:** {prod['product_name']} ({prod['product_code']})  ",
                 f"**Batch/Lot:** {batch}  ",
                 f"**Equipment:** {equip['equipment_id']} ({equip['equipment_name']})  ",
                 f"**Raised by:** {raised['full_name']} ({raised['role']})  ",
                 f"**Governing SOP:** {sop['sop_no']}  ", ""]
        instruction = (
            f"Write the fictional narrative body of a GMP '{template['form_name']}' "
            f"at {COMPANY}. Record {record_id}, product {prod['product_name']}, "
            f"batch {batch}, equipment {equip['equipment_id']}. 4-6 sentences: "
            f"describe the event/observation, immediate action, and disposition. "
            f"Realistic quality wording.")
        lines.append("## Description")
        lines.append(self._write(instruction, max_words=200))
        return "\n".join(lines)

    # -- Quality policy / manual prose (per-topic, so 15 docs aren't clones)
    def policy(self, reg: Registry, rng: random.Random,
               topic: str = "Quality Management System overview") -> str:
        sops = rng.sample(reg.sops, min(4, len(reg.sops)))
        ref_list = "; ".join(f"{s['sop_no']} ({s['title']})" for s in sops)
        instruction = (
            f"Write a fictional one-page policy document for {COMPANY}, a "
            f"botanical supplement manufacturer, on the topic: '{topic}' "
            f"(3-4 short paragraphs). Reference these procedures by number "
            f"where relevant: {ref_list}. Narrative prose, not step-by-step. "
            f"Realistic GMP tone.")
        return (f"# {COMPANY} — {topic}\n\n"
                + self._write(instruction, max_words=350))


def _pick_role(reg: Registry, role: str, rng: random.Random) -> dict:
    matches = [e for e in reg.employees if e["role"] == role]
    return rng.choice(matches) if matches else rng.choice(reg.employees)


