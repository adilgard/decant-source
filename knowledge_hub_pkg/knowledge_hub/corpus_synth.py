    def logs(self, reg: Registry, rng: random.Random) -> dict[str, str]:
        out = {}
        # Equipment cleaning log — rows reference equipment + operators.
        rows = []
        for i in range(max(12, len(reg.equipment) * 2)):
            eq = rng.choice(reg.equipment)
            op = rng.choice(reg.employees)
            ver = rng.choice(reg.employees)
            prod = rng.choice(reg.products)
            rows.append([f"2026-0{rng.randint(1,9)}-{rng.randint(10,28)}",
                         eq["equipment_id"], eq["equipment_name"],
                         prod["product_code"], f"B-2026-{rng.randint(1000,9999)}",
                         "Cleaning", op["employee_id"], ver["employee_id"],
                         "Clean"])
        out["tabular_cleaning"] = _csv(
            ["log_date", "equipment_id", "equipment_name", "product_code",
             "batch_lot_no", "activity_type", "done_by", "verified_by",
             "status"], rows)
        # Material receipt log — references vendor + material lots.
        rows = []
        for i, m in enumerate(reg.materials):
            rows.append([f"GRN-2026-{800 + i:05d}", m["material_id"],
                         m["material_name"], m["lot_no"], m["vendor_id"],
                         f"PO-2026-{1100 + i:05d}", "Released", m["expiry"]])
        out["tabular_receipts"] = _csv(
            ["grn_no", "material_id", "material_name", "material_lot_no",
             "vendor_id", "po_number", "qc_status", "expiry_date"], rows)
        return out


