# Orchestrator
# ---------------------------------------------------------------------------
class CorpusSynthesizer:
    def __init__(self, seed: int = 20260723, model: Optional[str] = None,
                 host: Optional[str] = None):
        self._seed = seed
        self._reg_builder = SeedRegistry(seed)
        self._narrator = NarrativeGenerator(model, host)
        self._tabular = TabularEmitter()

    def generate(self, out_dir: str | Path, scale: str = "pilot") -> dict:
        out = Path(out_dir)
        rng = random.Random(self._seed + 1)
        reg = self._reg_builder.build(scale)
        s = SCALES[scale]
        manifest: dict[str, Any] = {
            "company": COMPANY, "site": SITE, "scale": scale, "seed": self._seed,
            "generator_version": GENERATOR_VERSION, "model": self._narrator.model,
            "counts": {}, "sources": {}, "registry_sizes": {
                "employees": len(reg.employees), "vendors": len(reg.vendors),
                "customers": len(reg.customers), "products": len(reg.products),
                "materials": len(reg.materials), "equipment": len(reg.equipment),
                "sops": len(reg.sops)},
            "er_noise": reg.er_noise,
        }

        def emit(folder: str, filename: str, content: str,
                 config: dict[str, Any]) -> None:
            d = out / folder
            d.mkdir(parents=True, exist_ok=True)
            (d / filename).write_text(content, encoding="utf-8")
            manifest["sources"][folder] = config  # source_registry.config

        # SoR master tables + logs (deterministic) -> one source folder each,
        # carrying its structured_map so key columns become extracted_keys.
        sor_files = self._tabular.sor_tables(reg)
        log_files = self._tabular.logs(reg, rng)
        for folder, content in {**sor_files, **log_files}.items():
            doc_type, smap = STRUCTURED_MAPS[folder]
            cfg: dict[str, Any] = {"data_track": "structured", "doc_type": doc_type}
            if smap:
                cfg["structured_map"] = smap
            emit(folder, f"{folder}.csv", content, cfg)
        manifest["counts"]["sor_tabular"] = len(sor_files) + len(log_files)

        # Narrative docs (local model) -> per-track folders, each declaring its
        # doc_type (data_track=prose so they chunk + embed for retrieval).
        prose_cfg = lambda dt: {"data_track": "prose", "doc_type": dt}
        n_sop = 0
        sop_dir = out / "sop"; sop_dir.mkdir(parents=True, exist_ok=True)
        for sop in reg.sops[:s["n_sop"]]:
            md = self._narrator.sop(sop, reg, rng)
            (sop_dir / f"{sop['sop_no']}_{_slug(sop['title'])}.md").write_text(
                md, encoding="utf-8")
            n_sop += 1
        manifest["counts"]["sop"] = n_sop
        if n_sop:
            manifest["sources"]["sop"] = prose_cfg("sop")

        prose_dir = out / "prose"; prose_dir.mkdir(parents=True, exist_ok=True)
        for i in range(s["n_prose"]):
            topic = _POLICY_TOPICS[i % len(_POLICY_TOPICS)]
            (prose_dir / f"policy_{i + 1:02d}_{_slug(topic)[:40]}.md").write_text(
                self._narrator.policy(reg, rng, topic), encoding="utf-8")
        manifest["counts"]["prose"] = s["n_prose"]
        if s["n_prose"]:
            manifest["sources"]["prose"] = prose_cfg("prose")

        comm_dir = out / "communication"; comm_dir.mkdir(parents=True, exist_ok=True)
        comm_kinds = ["deviation", "release", "capa", "recall", "audit",
                      "supplier"]
        n_msgs = 0
        for i in range(s["n_comm"]):
            kind = comm_kinds[i % len(comm_kinds)]
            rid = f"{kind[:3].upper()}-2026-{100 + i:04d}"
            messages = self._narrator.comm_thread(
                kind, reg, rng, rid, with_reply=(i % 3 == 0))
            for m_ix, message in enumerate(messages):
                name = f"{rid}.txt" if m_ix == 0 else f"{rid}_re{m_ix}.txt"
                (comm_dir / name).write_text(message, encoding="utf-8")
                n_msgs += 1
        manifest["counts"]["communication"] = n_msgs
        if s["n_comm"]:
            manifest["sources"]["communication"] = prose_cfg("communication")

        form_dir = out / "form"; form_dir.mkdir(parents=True, exist_ok=True)
        for i in range(s["n_form"]):
            template = reg.forms[i % len(reg.forms)]
            rid = f"{_slug(template['form_no'])}-INST-{i + 1:03d}"
            (form_dir / f"{rid}.md").write_text(
                self._narrator.form(template, reg, rng, rid), encoding="utf-8")
        manifest["counts"]["form"] = s["n_form"]
        if s["n_form"]:
            manifest["sources"]["form"] = prose_cfg("form")

        (out / "corpus_manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8")
        return manifest
