"""Synthetic corpus generator (campaign phase) — grounded in public GMP
document research, generated by LOCAL models only (privacy fork intact).

See `.Progress Docs/Ongoing/KnowledgeHub_SyntheticCorpus_Spec_v0.1_2026-07-23.md`.

Two layers, mirroring the real pipeline:
  * SeedRegistry — a DETERMINISTIC, seeded backbone of entities (people,
    vendors, customers, products, materials, equipment, SOP numbers, forms)
    with the research's real ID formats. Pure code: no model, reproducible.
    This is what makes the corpus CONNECTED — every narrative doc references
    these IDs, so the same entity recurs across docs under varied surface
    forms (the entity-resolution target) and cross-doc chains exist for
    multi-hop retrieval.
  * NarrativeGenerator — a LOCAL Ollama model writes the PROSE for a
    structured brief the backbone hands it. IDs, references, supersession and
    the cross-reference graph are code-controlled (connectivity is not left to
    the model); only the wording is generated. Fictional throughout.

The tabular/SoR layer (master tables + logs as CSV) is pure code too, and
carries the deliberate ER noise (a vendor spelled two ways sharing a tax_id,
a lot number reused across vendors, an employee nicknamed across sheets).

CorpusSynthesizer.generate() writes files into a directory tree by track; the
real capture->process->extract->resolve pipeline ingests that tree via
FilesystemSourceAdapter (see scripts/build_corpus.py). Nothing here writes to
the DB directly — the pipeline owns that.
"""
